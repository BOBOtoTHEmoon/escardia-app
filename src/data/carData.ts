// Get models for a specific brand
export const getModelsForBrand = (brand: string): string[] => {
  // Try exact match first
  if (CAR_MODELS[brand]) {
    return CAR_MODELS[brand];
  }
  
  // Try case-insensitive match
  const brandLower = brand.toLowerCase();
  for (const [key, models] of Object.entries(CAR_MODELS)) {
    if (key.toLowerCase() === brandLower) {
      return models;
    }
  }
  
  // Return empty array if brand not found
  return [];
};

// Get all models (flat list)
export const getAllModels = (): string[] => {
  const allModels: string[] = [];
  for (const models of Object.values(CAR_MODELS)) {
    allModels.push(...models);
  }
  return [...new Set(allModels)].sort();
};

export default { CAR_BRANDS, CAR_MODELS, getModelsForBrand, getAllModels };